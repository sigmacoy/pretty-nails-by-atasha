import { NextRequest, NextResponse } from "next/server";
import { auth } from "@/lib/auth";
import { prisma } from "@/lib/db";
import { z } from "zod";

export const dynamic = "force-dynamic";

const stampSchema = z.object({
  qrCode: z.string(),
});

const SHOP_QR_CODE = "prettynails-shop-qr-code";
const STAMP_EXPIRY_MONTHS = 12;
const STAMP_PER_AMOUNT = 50000; // ₱500 in centavos

export async function POST(req: NextRequest) {
  try {
    const session = await auth();
    if (!session?.user?.id) {
      return NextResponse.json({ error: "Unauthorized. Please sign in to scan your stamp." }, { status: 401 });
    }

    const body = await req.json();
    const parsed = stampSchema.safeParse(body);

    if (!parsed.success) {
      return NextResponse.json({ error: "Invalid QR code format." }, { status: 400 });
    }

    const qrData = parsed.data.qrCode.trim();

    // Check if dynamic per-customer booking stamp QR (format: prettynails-stamp:<bookingId> or JSON)
    let bookingId: string | null = null;

    if (qrData.startsWith("prettynails-stamp:")) {
      bookingId = qrData.replace("prettynails-stamp:", "").trim();
    } else if (qrData.startsWith("{") && qrData.includes("bookingId")) {
      try {
        const decoded = JSON.parse(qrData);
        bookingId = decoded.bookingId;
      } catch (e) {}
    }

    let targetBooking = null;

    if (bookingId) {
      targetBooking = await prisma.booking.findUnique({
        where: { id: bookingId },
        include: {
          services: { include: { service: true } },
          loyaltyStamps: true,
        },
      });

      if (!targetBooking) {
        return NextResponse.json({ error: "Appointment not found for this QR code." }, { status: 404 });
      }

      if (targetBooking.userId !== session.user.id && session.user.role !== "ADMIN") {
        return NextResponse.json(
          { error: "This visit QR code belongs to another customer's booking. Please ensure you are logged into your own account." },
          { status: 403 }
        );
      }

      if (targetBooking.status === "CANCELLED" || targetBooking.status === "NO_SHOW") {
        return NextResponse.json(
          { error: "This appointment was cancelled or recorded as a no-show and is not eligible for loyalty stamps." },
          { status: 400 }
        );
      }

      // Check if already stamped
      if (targetBooking.loyaltyStamps.length > 0) {
        return NextResponse.json(
          { error: "This visit has already been stamped on your loyalty card." },
          { status: 400 }
        );
      }

      // Mark completed if not already
      if (targetBooking.status !== "COMPLETED") {
        await prisma.booking.update({
          where: { id: targetBooking.id },
          data: { status: "COMPLETED" },
        });
      }
    } else if (qrData === SHOP_QR_CODE) {
      // Find the user's latest completed booking without a stamp
      targetBooking = await prisma.booking.findFirst({
        where: {
          userId: session.user.id,
          status: "COMPLETED",
          loyaltyStamps: { none: {} },
        },
        orderBy: { appointmentDate: "desc" },
        include: {
          services: { include: { service: true } },
          loyaltyStamps: true,
        },
      });

      if (!targetBooking) {
        // If prototype demo, find any completed or confirmed booking of the user
        const anyBooking = await prisma.booking.findFirst({
          where: { userId: session.user.id },
          orderBy: { appointmentDate: "desc" },
          include: {
            services: { include: { service: true } },
            loyaltyStamps: true,
          },
        });

        if (anyBooking && anyBooking.loyaltyStamps.length === 0) {
          targetBooking = anyBooking;
          await prisma.booking.update({
            where: { id: anyBooking.id },
            data: { status: "COMPLETED" },
          });
        } else {
          return NextResponse.json(
            { error: "No completed appointment eligible for stamping found. Please complete your service first." },
            { status: 400 }
          );
        }
      }
    } else {
      return NextResponse.json(
        { error: "Invalid QR code. Please scan the QR code generated by Atasha." },
        { status: 400 }
      );
    }

    // Calculate stamps earned
    // Rule: 1 stamp per nail set OR 1 stamp per ₱500 paid amount; 2 stamps for ₱1,000+
    // If a customer only books Nail Cleaning (< ₱500 and no nail sets), 0 stamps are earned.
    const NAIL_SET_CATEGORIES = ["GEL", "EXTENSION", "PEDICURE"];
    const hasNailSet = targetBooking.services.some((s: any) => {
      const cat = s.service?.category?.toUpperCase() || "";
      const name = s.service?.name?.toLowerCase() || "";
      return (
        NAIL_SET_CATEGORIES.includes(cat) ||
        name.includes("gel") ||
        name.includes("extension") ||
        name.includes("pedicure")
      );
    });

    const amount = targetBooking?.totalPrice || 0;
    let stampsEarned = 0;
    let source = "SERVICE";

    if (amount >= 100000) {
      // ₱1,000+ gives 2 stamps
      stampsEarned = 2;
      source = "AMOUNT";
    } else if (hasNailSet) {
      // 1 stamp per nail set (Nail Gel, Soft Gel Extension, Nail Gel Pedicure)
      stampsEarned = 1;
      source = "SERVICE";
    } else if (amount >= STAMP_PER_AMOUNT) {
      // 1 stamp per ₱500 paid amount
      stampsEarned = Math.floor(amount / STAMP_PER_AMOUNT);
      source = "AMOUNT";
    } else {
      // Only Nail Cleaning (e.g. ₱200) without any nail sets and under ₱500
      stampsEarned = 0;
    }

    if (stampsEarned === 0) {
      return NextResponse.json(
        {
          error:
            "This appointment does not qualify for a loyalty stamp. Loyalty stamps require at least 1 nail set service (Nail Gel, Soft Gel Extension, Nail Gel Pedicure) or a minimum service total of ₱500.",
        },
        { status: 400 }
      );
    }

    // Get or create loyalty card for this customer
    let card = await prisma.loyaltyCard.findUnique({
      where: { userId: session.user.id },
    });

    const newExpiryAt = new Date(Date.now() + STAMP_EXPIRY_MONTHS * 30 * 24 * 60 * 60 * 1000);

    if (!card) {
      card = await prisma.loyaltyCard.create({
        data: {
          userId: session.user.id,
          stampCount: 0,
          expiresAt: newExpiryAt,
        },
      });
    }

    // If expired, reset count
    let currentStampCount = card.stampCount;
    if (card.expiresAt && new Date(card.expiresAt) < new Date()) {
      currentStampCount = 0;
    }

    const newStampCount = currentStampCount + stampsEarned;

    await prisma.$transaction([
      prisma.loyaltyCard.update({
        where: { id: card.id },
        data: {
          stampCount: newStampCount,
          lastStampAt: new Date(),
          expiresAt: newExpiryAt,
        },
      }),
      prisma.loyaltyStamp.create({
        data: {
          cardId: card.id,
          bookingId: targetBooking.id,
          source,
          amount,
        },
      }),
    ]);

    return NextResponse.json({
      success: true,
      stampCount: newStampCount,
      stampsEarned,
      message: `Earned ${stampsEarned} stamp${stampsEarned > 1 ? "s" : ""}! You now have ${newStampCount} stamps.`,
    });
  } catch (error) {
    console.error("Add stamp error:", error);
    return NextResponse.json({ error: "Failed to process stamp. Please try again." }, { status: 500 });
  }
}